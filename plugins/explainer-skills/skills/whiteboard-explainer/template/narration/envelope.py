"""Writes src/envelope.rs: narration loudness per video frame (0-255), for the host's talking bob.

    python -I narration/envelope.py      (build_vo.py and est_cues.py run it for you)
"""
import pathlib

import numpy as np
import soundfile as sf

ROOT = pathlib.Path(__file__).resolve().parent.parent
audio, sr = sf.read(ROOT / "audio" / "narration.wav", dtype="float32")
if audio.ndim > 1:
    audio = audio.mean(axis=1)
hop = sr // 30
n = len(audio) // hop
rms = np.sqrt((audio[: n * hop].reshape(n, hop) ** 2).mean(axis=1))
ref = np.percentile(rms[rms > 1e-4], 95) if (rms > 1e-4).any() else 1.0
env = np.clip(rms / ref, 0, 1)
vals = (env * 255).round().astype(int)
body = ",".join(str(v) for v in vals)
(ROOT / "src" / "envelope.rs").write_text(
    "// Generated by narration/envelope.py: narration loudness per frame (30 fps), 0-255.\n"
    f"pub const ENVELOPE: &[u8] = &[{body}];\n",
    encoding="utf-8", newline="\n",
)
print(f"envelope: {n} frames -> src/envelope.rs")
