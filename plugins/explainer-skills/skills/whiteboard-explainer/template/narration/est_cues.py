"""Provisional cues while the real voice isn't built yet: writes src/cues.rs with ESTIMATED word times (each word's
length proportional to its characters), a silent audio/narration.wav of the same length and a flat src/envelope.rs,
so scenes can be drawn and checked before the voice exists (no TTS, no GPU, standard library only).
build_vo.py overwrites all three with the real thing, and scenes keyed by c.w(beat, "word") re-time themselves.

    python -I narration/est_cues.py [seconds_per_char]      (default 0.060 = roughly the voice at TEMPO 1.06)
"""
import importlib.util
import json
import math
import pathlib
import re
import sys
import wave

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPC = float(sys.argv[1]) if len(sys.argv) > 1 else 0.060
LEAD, GAP, GAP_Q, PAUSE_LEN, TAIL, FPS = 0.35, 0.5, 0.7, 8.0, 0.5, 30  # keep in step with build_vo.py

spec = importlib.util.spec_from_file_location("script", ROOT / "narration" / "script.py")
script = importlib.util.module_from_spec(spec)
spec.loader.exec_module(script)


def key(w):
    return re.sub(r"[^a-z0-9]", "", w.lower())


rows, cursor = [], 0.0
for name, beats in script.SCENES:
    t, cues, ends, words = LEAD, [], [], []
    for beat in beats:
        cues.append(t)
        if beat == script.PAUSE:
            t += PAUSE_LEN
            ends.append(t)
            words.append([])
            continue
        ws = []
        for w in beat.split():
            d = SPC * (len(w) + 1) + (0.25 if w[-1] in ".?!" else 0.12 if w[-1] in ",:;" else 0.0)
            ws.append((w, t, t + SPC * len(w)))
            t += d
        words.append(ws)
        ends.append(t)
        t += GAP_Q if beat.endswith("?") else GAP
    dur = math.ceil((t - GAP + TAIL) * FPS - 1e-6) / FPS
    rows.append((name, cursor, dur, cues, ends, words))
    cursor += dur


def arr(values):
    return "&[" + ", ".join(f"{v:.3f}" for v in values) + "]"


def warr(ws):
    return "&[" + ", ".join(f"W {{ w: {json.dumps(key(w) or w.lower())}, t: {a:.3f}, e: {b:.3f} }}" for w, a, b in ws) + "]"


HEAD = """// PROVISIONAL (narration/est_cues.py, estimated times). build_vo.py replaces this file.

/// One spoken word: lowercase letters and digits only ("T4," -> "t4"), start and end in scene time.
#[derive(Debug)]
pub struct W {
    pub w: &'static str,
    pub t: f32,
    pub e: f32,
}

#[derive(Debug)]
pub struct SceneCues {
    pub name: &'static str,
    /// Video time where the scene starts.
    pub start: f32,
    pub dur: f32,
    /// Scene-relative start of each beat (narration line or quiz pause).
    pub beats: &'static [f32],
    /// Scene-relative end of each beat.
    pub ends: &'static [f32],
    /// Every word of each beat with its scene-relative timing.
    pub words: &'static [&'static [W]],
}
"""
rs = [HEAD, f"pub const TOTAL: f32 = {cursor:.3f};\n", "pub const SCENES: &[SceneCues] = &["]
for name, start, dur, cues, ends, words in rows:
    rs.append(f'    SceneCues {{ name: "{name}", start: {start:.3f}, dur: {dur:.3f}, beats: {arr(cues)}, ends: {arr(ends)}, '
              f'words: &[{", ".join(warr(w) for w in words)}] }},')
rs.append("];\n")
(ROOT / "src" / "cues.rs").write_text("\n".join(rs), encoding="utf-8", newline="\n")
(ROOT / "audio").mkdir(exist_ok=True)
with wave.open(str(ROOT / "audio" / "narration.wav"), "wb") as f:
    f.setnchannels(1)
    f.setsampwidth(2)
    f.setframerate(24000)
    f.writeframes(b"\0\0" * int(cursor * 24000))
n = int(cursor * FPS)
(ROOT / "src" / "envelope.rs").write_text(
    "// Generated by narration/est_cues.py (silent track): build_vo.py replaces it.\n"
    f"pub const ENVELOPE: &[u8] = &[{','.join(['0'] * n)}];\n", encoding="utf-8", newline="\n")
print(f"provisional cues: {len(rows)} scenes, {cursor:.1f} s ({cursor / 60:.1f} min)")
