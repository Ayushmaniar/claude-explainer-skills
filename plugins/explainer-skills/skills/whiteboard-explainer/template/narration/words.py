"""Writes narration/WORDS.md (every scene's beats with each word's key and start time) from src/cues.rs,
checks every c.w / c.wn / c.we call (and the scenes' local w / wn wrappers) in src/s_*.rs against it, and
checks that every scene in narration/script.py has a dispatch arm in src/lib.rs.

    python -I narration/words.py      -> "WORDS.md written; 0 bad word cues"
"""
import importlib.util
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
rs = (ROOT / "src" / "cues.rs").read_text(encoding="utf-8")
scenes = {}
for m in re.finditer(r'SceneCues \{ name: "(\w+)", start: ([\d.]+), dur: ([\d.]+), beats: &\[([^\]]*)\], ends: &\[([^\]]*)\], words: &\[(.*)\] \},', rs):
    name, start, dur = m.group(1), float(m.group(2)), float(m.group(3))
    beats = [float(x) for x in m.group(4).split(",") if x.strip()]
    ends = [float(x) for x in m.group(5).split(",") if x.strip()]
    groups = re.findall(r"&\[((?:W \{[^}]*\}(?:, )?)*)\]", m.group(6))
    words = [[(w, float(t)) for w, t in re.findall(r'W \{ w: "(\w*)", t: ([\d.]+)', g)] for g in groups]
    scenes[name] = (start, dur, beats, ends, words)

md = ["# Word timings (scene time, seconds)\n",
      "Generated by narration/words.py from src/cues.rs. Use `c.w(beat, \"key\")` for the start of a word,",
      "`c.wn(beat, \"key\", n)` for its n-th occurrence (0-based), `c.we(beat, \"key\")` for its end.",
      "`c.b(i)` / `c.e(i)` = start / end of beat i. An empty beat is the quiz thinking pause.\n"]
for name, (start, dur, beats, ends, words) in scenes.items():
    md.append(f"\n## {name}  (video {start:.1f}s, {dur:.1f}s long)\n")
    for i, ws in enumerate(words):
        body = " ".join(f"{w}@{t:.2f}" for w, t in ws) if ws else "*(pause)*"
        md.append(f"- **beat {i}** [{beats[i]:.2f}-{ends[i]:.2f}] {body}")
(ROOT / "narration" / "WORDS.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")

# Every scene of the script needs a dispatch arm in lib.rs, or it renders as the placeholder.
spec = importlib.util.spec_from_file_location("script", ROOT / "narration" / "script.py")
script = importlib.util.module_from_spec(spec)
spec.loader.exec_module(script)
lib = (ROOT / "src" / "lib.rs").read_text(encoding="utf-8")
arms = set(re.findall(r'"(\w+)"\s*=>\s*s_\w+::\w+\(t, c\)', lib))
bad = 0
for name, _ in script.SCENES:
    if name not in arms:
        bad += 1
        print(f"scene {name!r} has no dispatch arm in src/lib.rs (it would render as the placeholder)")
if [n for n, _ in script.SCENES] != list(scenes):
    print("src/cues.rs doesn't match narration/script.py: run build_vo.py (or est_cues.py) first")
    bad += 1

# Check scene code: which scene function handles which scene comes from lib.rs's match.
fn_scene = {f: s for s, f in re.findall(r'"(\w+)"\s*=>\s*s_\w+::(\w+)\(t, c\)', lib)}
for path in sorted((ROOT / "src").glob("s_*.rs")):
    src = path.read_text(encoding="utf-8")
    if "crate::placeholder" in src:
        print(f"{path.name}: still calls crate::placeholder")
        bad += 1
    for fm in re.finditer(r"pub fn (\w+)<'a>\(t: f32, c: &SceneCues\)", src):
        fn = fm.group(1)
        body_end = src.find("\npub fn ", fm.end())
        body = src[fm.end(): body_end if body_end > 0 else len(src)]
        scene = fn_scene.get(fn)
        if scene not in scenes:
            continue
        words = scenes[scene][4]
        for cm in re.finditer(r'(?<![A-Za-z_])(?:c\.)?w[ne]?\((\d+),\s*"([^"]+)"(?:,\s*(\d+))?\)', body):
            beat, word, nth = int(cm.group(1)), cm.group(2), int(cm.group(3) or 0)
            k = re.sub(r"[^a-z0-9]", "", word.lower())
            if beat >= len(words) or sum(1 for w, _ in words[beat] if w == k) <= nth:
                bad += 1
                print(f"{path.name}:{fn} ({scene}): w({beat}, {word!r}) not found")
print(f"WORDS.md written; {bad} bad word cues")
sys.exit(1 if bad else 0)
