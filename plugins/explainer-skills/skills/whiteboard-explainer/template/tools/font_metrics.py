"""Writes src/metrics.rs: Excalifont's advance widths (in em) for ASCII 32..126, read from media/Excalifont-Regular.ttf.
kit.rs's text_w() uses them to centre, underline and wipe handwriting. Re-run only if you swap the handwriting font.

    python -I tools/font_metrics.py      (needs fontTools: pip install fonttools)
"""
import pathlib

from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
font = TTFont(ROOT / "media" / "Excalifont-Regular.ttf")
upem = font["head"].unitsPerEm
cmap = font.getBestCmap()
hmtx = font["hmtx"]
adv = [round(hmtx[cmap[c]][0] / upem, 3) if c in cmap else 0.6 for c in range(32, 127)]
(ROOT / "src" / "metrics.rs").write_text(
    "// Generated by tools/font_metrics.py from media/Excalifont-Regular.ttf.\n"
    "/// Advance widths (em) of Excalifont for ASCII 32..=126, from the TTF.\n"
    f"pub const EXCALI_ADV: [f32; 95] = [{', '.join(str(a) for a in adv)}];\n",
    encoding="utf-8", newline="\n",
)
print("95 advance widths -> src/metrics.rs")
