"""Writes src/figs.rs: every image in figs/ (name without .png) with its pixel size, for Card::new / fit / crop.

    python -I tools/prep_figs.py      (needs Pillow; run after adding, cropping or replacing a figure)

Figures are PNGs. Crop a paper figure into its own file with Pillow (Image.open(..).crop((x0, y0, x1, y1)).save(..))
when only a panel is needed; keep the provenance (paper, figure number, page) in research/paper_notes.md.
"""
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
rows = []
for p in sorted((ROOT / "figs").glob("*.png")):
    with Image.open(p) as im:
        rows.append((p.stem, *im.size))
lines = ["// Generated by tools/prep_figs.py: figure files in figs/ and their pixel sizes.",
         "pub const FIGS: &[(&str, f32, f32)] = &["]
lines += [f'    ("{n}", {w:.1f}, {h:.1f}),' for n, w, h in rows]
lines += ["];", ""]
(ROOT / "src" / "figs.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(len(rows), "figures -> src/figs.rs")
